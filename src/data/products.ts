type NodeSpec = [id: string, type: string, name: string, col: number, row?: number];
const N = (specs: NodeSpec[]): WfNode[] => specs.map(([id, type, name, col, row = 0]) => ({ id, type, name, col, row }));
const C = (pairs: (readonly [string, string] | readonly [string, string, string])[]): WfConnection[] => pairs.map(([from, to, label]) => (label ? { from, to, label } : { from, to }));
const fromWorkflow = (id: string) => {
  const w = WORKFLOWS.find((x) => x.id === id)!;
  return { trigger: w.trigger, nodes: w.nodes, connections: w.connections };
};
const instancesOf = (productId: string, versions: Record<string, number> = {}) =>
  WORKFLOWS.filter((w) => w.productId === productId).map((w) => ({ workflowId: w.id, companyId: w.companyId, version: versions[w.id] ?? 0 }));

